# Create runtime/secrets/fengji_api.env on the deploy host (secrets stay on server; do not commit).
param(
    [Parameter(Mandatory = $true)]
    [string]$DatabaseUrl,
    [string]$Root = "C:\Users\Administrator\quant_futures",
    [switch]$AllowManualSubscriptionConfirm
)

$ErrorActionPreference = "Stop"
Set-Location $Root

$secretDir = Join-Path $Root "runtime\secrets"
New-Item -ItemType Directory -Force -Path $secretDir | Out-Null
$envPath = Join-Path $secretDir "fengji_api.env"

if (Test-Path -LiteralPath $envPath) {
    $backup = Join-Path $secretDir ("fengji_api.env.bak_" + (Get-Date -Format "yyyyMMdd_HHmmss"))
    Copy-Item -LiteralPath $envPath -Destination $backup -Force
    Write-Host "Backed up existing env to $(Split-Path $backup -Leaf)"
}

$jwtBytes = New-Object byte[] 48
[System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($jwtBytes)
$jwt = [Convert]::ToBase64String($jwtBytes) -replace '[+/=]', 'x'

$adminBytes = New-Object byte[] 32
[System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($adminBytes)
$admin = [Convert]::ToBase64String($adminBytes) -replace '[+/=]', 'x'

$manual = if ($AllowManualSubscriptionConfirm) { "1" } else { "0" }
$lines = @(
    "# Generated by scripts/remote/create_fengji_api_env.ps1 — do not commit",
    "DATABASE_URL=$DatabaseUrl",
    "FENGJI_JWT_SECRET=$jwt",
    "FENGJI_ADMIN_TOKEN=$admin",
    "FENGJI_ALLOW_MANUAL_SUBSCRIPTION_CONFIRM=$manual"
)
Set-Content -LiteralPath $envPath -Value ($lines -join "`n") -Encoding UTF8
Write-Host "Created $envPath (values not printed). JWT and ADMIN token are server-local only."
